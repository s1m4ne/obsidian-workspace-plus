var extendedLangs = Object.keys(EXTENDED_STRINGS);
for (var extendedLangIndex = 0; extendedLangIndex < extendedLangs.length; extendedLangIndex++) {
    var extendedLang = extendedLangs[extendedLangIndex];
    if (!STRINGS[extendedLang]) continue;
    var extendedKeys = Object.keys(EXTENDED_STRINGS[extendedLang]);
    for (var extendedKeyIndex = 0; extendedKeyIndex < extendedKeys.length; extendedKeyIndex++) {
        var extendedKey = extendedKeys[extendedKeyIndex];
        if (STRINGS[extendedLang][extendedKey] === undefined) {
            STRINGS[extendedLang][extendedKey] = EXTENDED_STRINGS[extendedLang][extendedKey];
        }
    }
}

